package org.twins.core.enums.datascope;

/**
 * Data scope of entity rows — which jurisdiction owns them. Combined in {@link org.twins.core.dao.annotation.DataScope}
 * arrays for tables that mix rows of different scopes.
 *
 * @see org.twins.core.dao.annotation.DataScope
 */
public enum DataScopeType {

    /**
     * Platform-level dictionaries and configuration, not owned by any domain (featurer registry,
     * i18n locales/types, link types, domain types, face components, identity providers, …).
     * Never copied by domain duplicate.
     */
    SYSTEM,

    /**
     * Domain settings / configuration rows (twin classes, factories, twinflows, data lists,
     * permission schemas, faces, tiers, schedulers, …). Copied by the domain settings duplicate.
     */
    DOMAIN,

    /**
     * Data generated by domain members while using the domain: twins and their fields/links/
     * markers/tags/comments/attachments, drafts, history, memberships (domain_user,
     * domain_business_account*), resources, runtime statistics. Never copied by domain duplicate.
     */
    DOMAIN_MEMBER,

    /**
     * Marker for tables holding rows owned by a concrete business account ({@code business_account_id}
     * column): BA-custom data list options, BA-level schema overrides, BA-scoped alias counters, …
     * Consumers: the future {@code domain_business_account/export/sql} API filters by
     * {@code business_account_id = :baId}. Combine with the row-nature scope
     * (e.g. {@code @DataScope({DOMAIN, BUSINESS_ACCOUNT})}).
     */
    BUSINESS_ACCOUNT
}
